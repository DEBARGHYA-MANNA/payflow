import { jsPDF } from "jspdf";
import { fmtINR, fmtDateTime, maskAccount } from "./format";
import { CURRENT_USER } from "../data/mock";

const COLORS = {
  ink: [14, 17, 23],
  muted: [110, 118, 132],
  line: [226, 229, 235],
  accent: [201, 242, 79],
  band: [10, 14, 20],
  good: [22, 163, 74],
  warn: [217, 119, 6],
  bad: [220, 38, 38],
};

const statusColor = {
  completed: COLORS.good,
  pending: COLORS.warn,
  failed: COLORS.bad,
};

/**
 * Generates and downloads a styled PDF receipt for a transaction.
 * jsPDF core fonts lack the ₹ glyph, so amounts use "INR".
 */
export function downloadReceipt(t) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const M = 56;
  let y = 0;

  // ---- header band
  doc.setFillColor(...COLORS.band);
  doc.rect(0, 0, W, 110, "F");
  doc.setFillColor(...COLORS.accent);
  doc.rect(0, 110, W, 5, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.setTextColor(255, 255, 255);
  doc.text("PayFlow", M, 48);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(160, 168, 180);
  doc.text("DIGITAL BANKING · INDIA · SIMULATION", M, 66);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(...COLORS.accent);
  doc.text("PAYMENT RECEIPT", W - M, 48, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(160, 168, 180);
  doc.text(t.reference, W - M, 66, { align: "right" });

  // ---- amount
  y = 195;
  doc.setFontSize(10);
  doc.setTextColor(...COLORS.muted);
  const isOut = t.amount < 0;
  doc.text(isOut ? "AMOUNT SENT" : "AMOUNT RECEIVED", W / 2, y, {
    align: "center",
    charSpace: 1.5,
  });
  y += 42;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(36);
  doc.setTextColor(...COLORS.ink);
  doc.text(fmtINR(Math.abs(t.amount)), W / 2, y, { align: "center" });

  // ---- status pill
  y += 28;
  const label = t.status.toUpperCase();
  doc.setFontSize(9);
  const tw = doc.getTextWidth(label) + 26;
  doc.setFillColor(...statusColor[t.status]);
  doc.roundedRect(W / 2 - tw / 2, y - 12, tw, 22, 11, 11, "F");
  doc.setTextColor(255, 255, 255);
  doc.text(label, W / 2, y + 3, { align: "center" });

  // ---- details table
  y += 60;
  const rows = [
    [isOut ? "To" : "From", t.name],
    [isOut ? "From" : "To", `${CURRENT_USER.name} · A/c ${maskAccount(CURRENT_USER.account)}`],
    ["Date", fmtDateTime(t.date)],
    ["Method", t.method || "—"],
    ["Category", t.category || "—"],
    ["Reference", t.reference],
  ];
  if (t.note) rows.push(["Note", t.note]);
  if (t.status === "failed" && t.failureReason) rows.push(["Reason", t.failureReason]);

  rows.forEach(([k, v]) => {
    doc.setDrawColor(...COLORS.line);
    doc.setLineWidth(1);
    doc.line(M, y - 14, W - M, y - 14);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(...COLORS.muted);
    doc.text(k, M, y);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...COLORS.ink);
    const maxW = W - M * 2 - 130;
    const wrapped = doc.splitTextToSize(String(v), maxW);
    doc.text(wrapped, W - M, y, { align: "right" });
    y += wrapped.length > 1 ? 34 * wrapped.length * 0.75 : 34;
  });
  doc.setDrawColor(...COLORS.line);
  doc.line(M, y - 14, W - M, y - 14);

  // ---- totals
  y += 26;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(...COLORS.muted);
  doc.text("Transfer fee", M, y);
  doc.setTextColor(...COLORS.ink);
  doc.text("INR 0.00", W - M, y, { align: "right" });
  y += 26;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Total", M, y);
  doc.text(fmtINR(Math.abs(t.amount)), W - M, y, { align: "right" });

  // ---- footer
  const FY = 760;
  doc.setFillColor(245, 246, 248);
  doc.roundedRect(M, FY, W - M * 2, 56, 8, 8, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(...COLORS.muted);
  doc.text("SIMULATED TRANSACTION", M + 16, FY + 22);
  doc.setFont("helvetica", "normal");
  doc.text(
    "This receipt was generated by PayFlow, a banking simulation. No real funds were moved.",
    M + 16,
    FY + 38
  );
  doc.setFontSize(8);
  doc.setTextColor(170, 176, 186);
  doc.text(
    `payflow.in · Kolkata · Generated ${fmtDateTime(new Date().toISOString())}`,
    W / 2,
    FY + 84,
    { align: "center" }
  );

  doc.save(`PayFlow-receipt-${t.reference}.pdf`);
}
